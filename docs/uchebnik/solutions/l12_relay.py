# Каждый дрон слетает вверх по своему столбцу и назад; остальные ждут.
from litebee_show import Show

show = Show('Эстафета')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.code(13, 1)
d.rgb('green')
d.code(49, 4)
d.code(13, 4)
d.rgb('blue')
d.set_z(100, 18)
d.land()

d = show.drone(2)
d.calibrate(5)
