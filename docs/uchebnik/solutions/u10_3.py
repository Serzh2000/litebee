# Упражнение 10.3: один летит по квадрату, второй висит выше и мигает.
from litebee_show import Show

show = Show('Облёт вокруг лампы')

d = show.drone(1)
d.calibrate(5)
d.takeoff(80, 5)
d.rgb('green')
d.code(13, 1)
d.code_s('16 52 49 13', 16)
d.land()

d = show.drone(2)
d.calibrate(5)
d.takeoff(150, 5)
d.code(27, 1)
d.rgb('red')
d.set_z(150, 2)
d.rgb('black')
d.set_z(150, 2)
d.rgb('red')
d.set_z(150, 2)
d.rgb('black')
d.set_z(150, 2)
d.rgb('red')
d.set_z(150, 2)
d.rgb('black')
d.set_z(150, 2)
d.rgb('red')
d.set_z(150, 2)
d.rgb('black')
d.set_z(150, 2)
d.land()
