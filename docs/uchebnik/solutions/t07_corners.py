# Проект 3. Четыре дрона стоят по углам квадрата 5 x 5 клеток и обходят его по кругу.
from litebee_show import Show

show = Show('Углы по кругу')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('red')
d.code(0, 1)
d.code(4, 4)
d.code(52, 4)
d.code(48, 4)
d.code(0, 4)
d.rgb('black')
d.land()

