# Мастер-класс: шоу из четырёх дронов. Полное решение (для ведущего).
# Четверть коврика 6 x 6 клеток. Дроны стоят по углам квадрата: 13, 16, 52, 49.
# Сцены: взлёт (0-11 с), квадрат (11-23 с), волна (23-33 с), карусель (33-45 с), посадка.
from litebee import Show

show = Show('Мастер-класс: четыре дрона')

# ---------- Дрон 1: зелёный, стоит на клетке 13
d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('green')
d.code(13, 1)
# Сцена 1. Квадрат: по 3 с на сторону
d.code(16, 3)
d.code(52, 3)
d.code(49, 3)
d.code(13, 3)
# Сцена 2. Волна: дрон 1 поднимается первым
d.rgb('white')
d.set_z(140, 2)
d.set_z(100, 2)
d.rgb('green')
d.set_z(100, 6)
# Сцена 3. Карусель: два полукруга вокруг центра квадрата
d.rgb('cyan')
d.circle(1, 13, 52, 6)
d.circle(1, 13, 52, 6)
# Посадка на свою клетку
d.rgb('green')
d.land_on(13)

# ---------- Дрон 2: синий, стоит на клетке 16
d = show.drone(2)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('blue')
d.code(16, 1)
d.code(52, 3)
d.code(49, 3)
d.code(13, 3)
d.code(16, 3)
d.set_z(100, 2)
d.rgb('white')
d.set_z(140, 2)
d.set_z(100, 2)
d.rgb('blue')
d.set_z(100, 4)
d.rgb('cyan')
d.circle(1, 13, 52, 6)
d.circle(1, 13, 52, 6)
d.rgb('blue')
d.land_on(16)

# ---------- Дрон 3: жёлтый, стоит на клетке 52
d = show.drone(3)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('yellow')
d.code(52, 1)
d.code(49, 3)
d.code(13, 3)
d.code(16, 3)
d.code(52, 3)
d.set_z(100, 4)
d.rgb('white')
d.set_z(140, 2)
d.set_z(100, 2)
d.rgb('yellow')
d.set_z(100, 2)
d.rgb('cyan')
d.circle(1, 13, 52, 6)
d.circle(1, 13, 52, 6)
d.rgb('yellow')
d.land_on(52)

# ---------- Дрон 4: красный, стоит на клетке 49
