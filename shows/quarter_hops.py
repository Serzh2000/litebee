# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Четыре дрона на углах. Каждый по очереди прыгает на одну клетку к центру и возвращается, пока остальные ждут.
from litebee_show import Show

show = Show('Прыжки по очереди в четверти')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('green')
d.code(13, 1)
d.rgb('white')
d.code(26, 3)
d.set_z(100, 1)
d.rgb('green')
d.code(13, 3)
d.set_z(100, 18)
d.rgb('black')
d.land()

