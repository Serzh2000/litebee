# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Только свет: первый дрон зажигает цвет и гаснет, второй отвечает тем же цветом. Дроны стоят на месте.
# Посадка land_on: дрон подлетает к клетке, замирает, снижается и только потом садится: так он садится ровнее.
from litebee_show import Show

show = Show('Диалог света')

d = show.drone(1)
d.calibrate(5)
d.takeoff(80, 5)
d.rgb('black')
d.code(13, 1)
d.rgb('red')
d.set_z(80, 2)
d.rgb('black')
d.set_z(80, 2)
d.rgb('blue')
d.set_z(80, 2)
d.rgb('black')
d.set_z(80, 2)
d.rgb('green')
d.set_z(80, 2)
d.rgb('black')
d.set_z(80, 2)
d.rgb('yellow')
d.set_z(80, 2)
d.rgb('black')
d.set_z(80, 2)
d.rgb('purple')
d.set_z(80, 2)
d.rgb('black')
d.set_z(80, 2)
d.rgb('cyan')
d.set_z(80, 2)
d.rgb('black')
d.set_z(80, 2)
d.rgb('black')
d.land_on(13)

