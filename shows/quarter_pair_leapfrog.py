# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Два дрона идут вдоль одной строки и по очереди обгоняют друг друга: пока один проходит над другим, высоты 70 и 150 см.
# Посадка land_on: дрон подлетает к клетке, замирает, снижается и только потом садится: так он садится ровнее.
from litebee_show import Show

show = Show('Чехарда')

d = show.drone(1)
d.calibrate(5)
d.takeoff(70, 5)
d.rgb('yellow')
d.code(12, 1)
d.code(14, 3)
d.code(16, 3)
d.code(17, 2)
d.rgb('black')
d.land_on(17)

d = show.drone(2)
d.calibrate(5)
d.takeoff(150, 5)
d.rgb('cyan')
d.code(14, 1)
d.code(15, 3)
d.code(14, 3)
d.code(14, 2)
d.rgb('black')
d.land_on(14)
