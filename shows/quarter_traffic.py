# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Три дрона стоят через клетку и по очереди показывают красный, жёлтый и зелёный.
# Хороший первый пример: только свет и ожидание, никто не летает по коврику.
from litebee_show import Show

show = Show('Светофор в четверти')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.code(13, 1)
d.rgb('red')
d.set_z(100, 4)
d.rgb('yellow')
d.set_z(100, 4)
d.rgb('green')
d.set_z(100, 4)
d.rgb('red')
d.set_z(100, 4)
d.rgb('yellow')
d.set_z(100, 4)
d.rgb('green')
d.set_z(100, 4)
d.rgb('black')
d.land()

