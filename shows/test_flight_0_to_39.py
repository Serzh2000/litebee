# Проверочный полёт одного дрона: с клетки 0 в клетку 39 (3 клетки вправо, 3 вверх, это 170 см по диагонали).
# Дрон стоит на клетке 0. Короткий старт d.code(0, 1) даёт ему позицию на коврике, потом 8 секунд лёту
# (около 21 см/с, спокойно), посадка на месте прилёта. Высота 100 см.
from litebee_show import Show

show = Show('Проверка: клетка 0 в клетку 39')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('green')
d.code(0, 1)
d.code(39, 8)
d.rgb('black')
d.land()
