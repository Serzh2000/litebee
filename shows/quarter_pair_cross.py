# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Два дрона летят по диагоналям навстречу и проходят друг над другом: один на 80 см, другой на 150 см.
# Посадка land_on: дрон подлетает к клетке, замирает, снижается и только потом садится: так он садится ровнее.
from litebee_show import Show

show = Show('Разминуться')

d = show.drone(1)
d.calibrate(5)
d.takeoff(80, 5)
d.rgb('blue')
d.code(13, 1)
d.code(52, 7)
d.rgb('black')
d.land_on(52)

d = show.drone(2)
d.calibrate(5)
d.takeoff(150, 5)
d.rgb('red')
d.code(16, 1)
d.code(49, 7)
d.rgb('black')
d.land_on(49)
