# Для всего коврика 12 x 12 клеток (4,8 x 4,8 м), клетка = столбец + 12 x строка. Дроны стоят через клетку и больше.
# Четыре дрона из углов коврика летят к середине (углы квадрата 3 x 3 клетки), мигают белым и возвращаются.
from litebee_show import Show

show = Show('Углы к центру')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('green')
d.code(0, 1)
d.code(52, 8)
d.rgb('white')
d.set_z(100, 4)
d.rgb('green')
d.code(0, 8)
d.rgb('black')
d.land()

