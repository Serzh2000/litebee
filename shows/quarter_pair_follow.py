# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Второй дрон идёт по тому же квадрату, что и первый, на 4 секунды позже, и выше (150 против 80 см). Стартует он на две клетки выше первого.
# Посадка land_on: дрон подлетает к клетке, замирает, снижается и только потом садится: так он садится ровнее.
from litebee_show import Show

show = Show('Догонялки')

d = show.drone(1)
d.calibrate(5)
d.takeoff(80, 5)
d.rgb('red')
d.code(13, 1)
d.code(16, 4)
d.code(52, 4)
d.code(49, 4)
d.code(13, 4)
d.rgb('black')
d.land_on(13)

d = show.drone(2)
d.calibrate(5)
d.takeoff(150, 5)
d.rgb('blue')
d.code(37, 1)
d.set_z(150, 4)
d.code(16, 4)
d.code(52, 4)
d.code(49, 4)
d.code(13, 4)
d.rgb('black')
d.land_on(37)
