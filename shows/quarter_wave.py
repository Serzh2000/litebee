# Волна высоты в одной четверти коврика. Четыре дрона по очереди поднимаются на 150 см и опускаются.
# Дроны стоят через клетку (80 см друг от друга): клетки 13, 15, 51 и 49.
# Ожидание своей очереди записано как set_z на той же высоте.
from litebee_show import Show

show = Show('Волна в четверти')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.code(13, 1)
d.rgb('blue')
d.set_z(100, 0.1)
d.rgb('green')
d.set_z(150, 2)
d.rgb('yellow')
d.set_z(100, 2)
d.rgb('blue')
d.set_z(100, 6)
d.rgb('black')
d.land()

d = show.drone(2)
d.calibrate(5)
