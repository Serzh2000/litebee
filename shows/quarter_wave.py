d.code(15, 1)
d.rgb('blue')
d.set_z(100, 2)
d.rgb('green')
d.set_z(150, 2)
d.rgb('yellow')
d.set_z(100, 2)
d.rgb('blue')
d.set_z(100, 4)
d.rgb('black')
d.land()

d = show.drone(3)
