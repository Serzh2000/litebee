# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Четыре дрона на углах. Белый цвет и подъём на 130 см по очереди переходят от первого дрона к четвёртому.
from litebee_show import Show

show = Show('Эстафета света в четверти')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.code(13, 1)
d.rgb('white')
d.set_z(130, 3)
d.rgb('blue')
d.set_z(100, 3)
d.rgb('blue')
d.set_z(100, 3)
d.rgb('blue')
d.set_z(100, 3)
d.rgb('green')
d.set_z(100, 3)
d.rgb('black')
d.land()

