# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Четыре дрона обходят квадрат по краям и возвращаются на свои места, пятый висит над центром и меняет цвет.
# Перед загрузкой каждый дрон стоит на своей первой клетке (на карте она подсвечена), дальше номер подтянется сам.
from litebee_show import Show

show = Show('Пятёрка: хоровод и центр')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('red')
d.code(0, 1)
d.code(48, 4)
d.rgb('yellow')
d.code(52, 4)
d.rgb('green')
d.code(4, 4)
d.rgb('cyan')
d.code(0, 4)
d.rgb('red')
d.rgb('black')
d.land_on(0)

