# 2 дрона летят из ровной сетки в строи: кольцо → буква г → арка, всё это 2 раза и возвращаются.
# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Перед загрузкой каждый дрон стоит на своей первой клетке (на карте она подсвечена), номер подтянется сам.
from litebee_show import Show

show = Show('Кольцо → Буква Г → Арка ×2')

d = show.drone(1)
d.calibrate(5)
d.takeoff(150, 5)
d.rgb('red')
d.code(0, 1)
d.code(25, 4)
d.rgb('red')
d.set_z(150, 5)
d.code(25, 2)
d.rgb('yellow')
d.set_z(150, 5)
d.code(25, 2)
d.rgb('green')
d.set_z(150, 5)
d.code(25, 2)
d.rgb('cyan')
d.set_z(150, 5)
d.code(25, 2)
d.rgb('blue')
d.set_z(150, 5)
d.code(25, 2)
d.rgb('purple')
d.set_z(150, 5)
d.code(0, 4)
d.rgb('white')
d.set_z(150, 5)
d.rgb('black')
d.land_on(0)

