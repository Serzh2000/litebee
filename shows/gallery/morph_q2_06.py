# 2 дрона летят из ровной сетки в строи: арка → два ряда → диагональ, всё это 2 раза и возвращаются.
# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Перед загрузкой каждый дрон стоит на своей первой клетке (на карте она подсвечена), номер подтянется сам.
from litebee_show import Show

show = Show('Арка → Два ряда → Диагональ ×2')

d = show.drone(1)
d.calibrate(5)
d.takeoff(130, 5)
d.rgb('red')
d.code(0, 1)
d.code(26, 5)
d.rgb('red')
d.set_z(130, 5)
d.code(2, 4)
d.rgb('yellow')
d.set_z(130, 5)
d.code(13, 3)
d.rgb('green')
d.set_z(130, 5)
d.code(26, 3)
d.rgb('cyan')
d.set_z(130, 5)
d.code(2, 4)
d.rgb('blue')
d.set_z(130, 5)
d.code(13, 3)
d.rgb('purple')
d.set_z(130, 5)
d.code(0, 6)
d.rgb('white')
d.set_z(130, 5)
d.rgb('black')
d.land_on(0)

