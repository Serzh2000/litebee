# 2 дрона летят из ровной сетки в строи: буква г → колонна → арка, всё это 2 раза и возвращаются.
# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Перед загрузкой каждый дрон стоит на своей первой клетке (на карте она подсвечена), номер подтянется сам.
from litebee_show import Show

show = Show('Буква Г → Колонна → Арка ×2')

d = show.drone(1)
d.calibrate(5)
d.takeoff(150, 5)
d.rgb('red')
d.code(0, 1)
d.code(27, 6)
d.rgb('red')
d.set_z(150, 8)
d.code(38, 3)
d.rgb('yellow')
d.set_z(150, 8)
d.code(27, 3)
d.rgb('green')
d.set_z(150, 8)
d.code(27, 2)
d.rgb('cyan')
d.set_z(150, 8)
d.code(38, 3)
d.rgb('blue')
d.set_z(150, 8)
d.code(27, 3)
d.rgb('purple')
d.set_z(150, 8)
d.code(0, 6)
d.rgb('white')
d.set_z(150, 8)
d.rgb('black')
d.land_on(0)

