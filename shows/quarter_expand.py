# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Четыре дрона стоят квадратом 3 x 3 клетки, расходятся по углам четверти, мигают белым и собираются обратно.
from litebee_show import Show

show = Show('Раскрытие в четверти')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('green')
d.code(13, 1)
d.code(0, 6)
d.rgb('white')
d.set_z(100, 2)
d.rgb('green')
d.code(13, 6)
d.rgb('black')
d.land()

