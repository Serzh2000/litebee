# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Два дрона на противоположных углах кружатся вокруг центра (между клетками 26 и 39), потом в обратную сторону.
# Направление кругов в симуляторе угадано: на живом дроне проверьте, куда он повернёт.
from litebee_show import Show

show = Show('Двойная звезда в четверти')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('red')
d.code(13, 1)
d.circle(2, 26, 39, 10, 'cw')
d.rgb('green')
d.circle(2, 26, 39, 10, 'ccw')
d.rgb('black')
d.land()

d = show.drone(2)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('blue')
d.code(52, 1)
d.circle(2, 26, 39, 10, 'cw')
d.rgb('green')
d.circle(2, 26, 39, 10, 'ccw')
d.rgb('black')
d.land()
