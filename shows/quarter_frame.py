# Для одной четверти коврика: клетки 0-5 по столбцам и строкам (2,4 x 2,4 м), клетка = столбец + 12 x строка.
# Чтобы перенести шоу в другую четверть, нажмите «Перенести шоу» над картой.
# Три дрона держат строй (80 см между ними): шаг вправо, вперёд, влево и назад, на каждом шаге свой цвет.
from litebee_show import Show

show = Show('Строй идёт по рамке в четверти')

d = show.drone(1)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('green')
d.code(12, 1)
d.rgb('green')
d.code(13, 4)
d.rgb('blue')
d.code(49, 6)
d.rgb('yellow')
d.code(48, 4)
d.rgb('red')
d.code(12, 6)
d.rgb('black')
d.land()

d = show.drone(2)
d.calibrate(5)
d.takeoff(100, 5)
d.rgb('blue')
d.code(14, 1)
d.rgb('green')
d.code(15, 4)
d.rgb('blue')
d.code(51, 6)
d.rgb('yellow')
d.code(50, 4)
d.rgb('red')
d.code(14, 6)
d.rgb('black')
d.land()

d = show.drone(3)
d.calibrate(5)
